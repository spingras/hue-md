// Shared by sync.cjs (the /hue-md:github skill) and after-write.cjs (the hook).
// Writes the GitHub Markdown copy of a .hue.md file next to it, and never
// overwrites a .md file that hue-md did not generate unless forced.
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')

const CLI = path.join(__dirname, 'hue-md.cjs')

function downgrade (file) {
  return execFileSync(process.execPath, [CLI, 'downgrade', file], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
}

const MARKER_PREFIX = '<!-- Generated by hue-md from '

function targetFor (hueFile) {
  return hueFile.replace(/\.hue\.md$/i, '.md')
}

function isGenerated (mdFile) {
  try {
    const fd = fs.openSync(mdFile, 'r')
    const buf = Buffer.alloc(200)
    const n = fs.readSync(fd, buf, 0, buf.length, 0)
    fs.closeSync(fd)
    return buf.toString('utf8', 0, n).replace(/^﻿/, '').startsWith(MARKER_PREFIX)
  } catch {
    return false
  }
}

// Returns { status: 'written' | 'refused' | 'skipped', target, reason? }
function syncFile (hueFile, { force = false } = {}) {
  if (!/\.hue\.md$/i.test(hueFile)) return { status: 'skipped', target: null, reason: 'not a .hue.md file' }
  const target = targetFor(hueFile)
  if (fs.existsSync(target) && !force && !isGenerated(target)) {
    return { status: 'refused', target, reason: `${target} exists and was not generated by hue-md` }
  }
  const name = path.basename(hueFile)
  const header = `${MARKER_PREFIX}${name}. Edit ${name} instead of this file. -->\n\n`
  fs.writeFileSync(target, header + downgrade(hueFile))
  return { status: 'written', target }
}

module.exports = { syncFile, targetFor, isGenerated, MARKER_PREFIX }
