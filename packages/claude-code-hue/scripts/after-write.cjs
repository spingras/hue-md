#!/usr/bin/env node
// PostToolUse hook: after Claude writes or edits a .hue.md file, write the
// GitHub Markdown copy next to it. Off unless the user enabled auto_downgrade.
// Never blocks Claude: every failure exits 0 and is reported as context.
'use strict'

const path = require('node:path')
const { syncFile } = require('./sync-lib.cjs')

function report (text) {
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: { hookEventName: 'PostToolUse', additionalContext: text }
  }))
}

let input = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', (c) => { input += c })
process.stdin.on('end', () => {
  if (String(process.env.CLAUDE_PLUGIN_OPTION_AUTO_DOWNGRADE).toLowerCase() !== 'true') return
  let file
  try {
    const event = JSON.parse(input)
    file = event.tool_input && (event.tool_input.file_path || event.tool_input.path)
    if (file && !path.isAbsolute(file) && event.cwd) file = path.join(event.cwd, file)
  } catch {
    return
  }
  if (!file || !/\.hue\.md$/i.test(file)) return

  try {
    const r = syncFile(file)
    if (r.status === 'written') report(`hue-md: updated the GitHub copy ${r.target}.`)
    else if (r.status === 'refused') report(`hue-md: did not update ${r.target}: it exists and was not generated by hue-md. Ask the user before overwriting it (/hue-md:github).`)
  } catch (err) {
    report(`hue-md: could not write the GitHub copy of ${file}: ${err.message}`)
  }
})
