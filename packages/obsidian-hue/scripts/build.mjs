// Builds the three files Obsidian loads from .obsidian/plugins/hue-md/:
//   main.js        src/main.js bundled with the real Hue parser (src/index.js at the repo root)
//   manifest.json  src/manifest.json with the version from the root package.json
//   styles.css     the shared Hue stylesheet, colors following Obsidian's light/dark theme
//
// Run from anywhere: node packages/obsidian-hue/scripts/build.mjs
// Needs the root dev dependencies (esbuild): run `npm install` at the repo root once.

import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { css } from '../../../src/index.js'
import { COLORS } from '../../../src/palette.js'

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const root = path.resolve(pkgDir, '..', '..')
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version

const banner = `/* Hue MD for Obsidian ${version}. Generated by scripts/build.mjs from src/; do not edit. https://github.com/spingras/hue-md */`

await build({
  entryPoints: [path.join(pkgDir, 'src', 'main.js')],
  outfile: path.join(pkgDir, 'main.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['obsidian', 'electron', '@codemirror/*', '@lezer/*'],
  banner: { js: banner },
  legalComments: 'none',
  logLevel: 'warning'
})

const manifest = JSON.parse(fs.readFileSync(path.join(pkgDir, 'src', 'manifest.json'), 'utf8'))
manifest.version = version
fs.writeFileSync(path.join(pkgDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

// Obsidian's theme is picked in the app and can differ from the OS, so the
// colors follow body.theme-light / body.theme-dark. Variables set on <body>
// win over the :root ones in the shared stylesheet.
const vars = (mode) => [
  '  --hue-text: var(--text-normal);',
  `  --hue-neutral-bg: ${COLORS.gray[mode].bg};`,
  ...Object.entries(COLORS).map(([n, c]) => `  --hue-${n}: ${c[mode].fg};\n  --hue-${n}-bg: ${c[mode].bg};`)
].join('\n')

const styles = [
  banner,
  css(),
  `/* Obsidian theme colors, from src/palette.js */\nbody.theme-light {\n${vars('light')}\n}\nbody.theme-dark {\n${vars('dark')}\n}\n`,
  fs.readFileSync(path.join(pkgDir, 'src', 'obsidian.css'), 'utf8')
].join('\n')
fs.writeFileSync(path.join(pkgDir, 'styles.css'), styles)

const kb = (f) => (fs.statSync(path.join(pkgDir, f)).size / 1024).toFixed(1) + ' KB'
console.log(`hue-md obsidian ${version}: main.js ${kb('main.js')}, manifest.json, styles.css ${kb('styles.css')}`)
