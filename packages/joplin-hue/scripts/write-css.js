// Prepares build inputs from the repo root, so the plugin ships the same CSS
// and demo as every other Hue surface. Runs as the first step of `npm run dist`:
//   src/hue-md.css             from the shared stylesheet generator (src/index.js)
//   src/demoNote.generated.ts  demo/demo.hue.md, for Tools → Hue MD → New demo note
// webpack then copies the CSS to dist/ and bundles the demo into index.js.

const fs = require('fs')
const path = require('path')
const { pathToFileURL } = require('url')

const root = path.resolve(__dirname, '..', '..', '..')
const srcDir = path.resolve(__dirname, '..', 'src')

import(pathToFileURL(path.join(root, 'src', 'index.js')).href).then(({ css }) => {
	const cssOut = path.join(srcDir, 'hue-md.css')
	fs.writeFileSync(cssOut, css())

	const demo = fs.readFileSync(path.join(root, 'demo', 'demo.hue.md'), 'utf8')
	const demoOut = path.join(srcDir, 'demoNote.generated.ts')
	fs.writeFileSync(demoOut, `// Generated by scripts/write-css.js from demo/demo.hue.md. Do not edit.\nexport default ${JSON.stringify(demo)};\n`)

	console.log(`wrote ${path.relative(process.cwd(), cssOut)} and ${path.relative(process.cwd(), demoOut)}`)
}).catch((error) => {
	console.error(error)
	process.exit(1)
})
