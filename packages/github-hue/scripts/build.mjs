// Builds the GitHub browser integrations from src/content.js and the real Hue parser:
//   extension/content.js     content script for the Chrome / Edge / Firefox extension
//   extension/hue.css        shared Hue stylesheet with GitHub light/dark colors
//   extension/manifest.json  version from the root package.json
//   userscript/hue-md.user.js  the same script with the stylesheet inlined, for Tampermonkey / Violentmonkey
//
// Run from the repo root: node packages/github-hue/scripts/build.mjs
// Needs the root dev dependencies (esbuild): run `npm install` at the repo root once.

import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { css } from '../../../src/index.js'
import { COLORS, PAGE } from '../../../src/palette.js'

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const root = path.resolve(pkgDir, '..', '..')
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version
const notice = `Hue MD for GitHub ${version}. Generated by packages/github-hue/scripts/build.mjs from src/; do not edit. https://github.com/spingras/hue-md`

// GitHub picks light or dark on <html data-color-mode> (light, dark, or auto =
// follow the OS), with data-light-theme / data-dark-theme naming the theme for
// each. Variables on .markdown-body win over the :root ones in the shared sheet.
const vars = (mode) => [
  `  --hue-text: var(--fgColor-default, var(--color-fg-default, ${PAGE[mode].text}));`,
  `  --hue-neutral-bg: ${COLORS.gray[mode].bg};`,
  ...Object.entries(COLORS).map(([n, c]) => `  --hue-${n}: ${c[mode].fg};\n  --hue-${n}-bg: ${c[mode].bg};`)
].join('\n')
const MB = ' .markdown-body'
const themeCss = `/* GitHub theme colors, from src/palette.js */
[data-color-mode]${MB},
[data-color-mode="dark"][data-dark-theme^="light"]${MB} {
${vars('light')}
}
[data-color-mode="dark"]${MB},
[data-color-mode="light"][data-light-theme^="dark"]${MB} {
${vars('dark')}
}
@media (prefers-color-scheme: dark) {
  [data-color-mode="auto"]${MB} {
${vars('dark')}
  }
  [data-color-mode="auto"][data-dark-theme^="light"]${MB} {
${vars('light')}
  }
}
@media (prefers-color-scheme: light) {
  [data-color-mode="auto"][data-light-theme^="dark"]${MB} {
${vars('dark')}
  }
}
`
const styles = [
  `/* ${notice} */`,
  css(),
  themeCss,
  fs.readFileSync(path.join(pkgDir, 'src', 'github.css'), 'utf8')
].join('\n')
fs.writeFileSync(path.join(pkgDir, 'extension', 'hue.css'), styles)

const common = {
  entryPoints: [path.join(pkgDir, 'src', 'content.js')],
  bundle: true,
  format: 'iife',
  globalName: 'HueMD',
  platform: 'browser',
  target: 'es2020',
  legalComments: 'none',
  logLevel: 'warning'
}

await build({
  ...common,
  outfile: path.join(pkgDir, 'extension', 'content.js'),
  banner: { js: `/* ${notice} */` },
  define: { __HUE_CSS__: 'null' }
})

const manifestPath = path.join(pkgDir, 'extension', 'manifest.json')
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
manifest.version = version
manifest.description = 'Renders Hue MD on GitHub: colored spans, diff spans, key caps, progress bars, multi-state tasks and callout boxes.'
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')

const header = `// ==UserScript==
// @name         Hue MD for GitHub
// @namespace    https://spingras.github.io/hue-md/
// @version      ${version}
// @description  Renders Hue MD on GitHub: colored spans, diff spans, key caps, progress bars, multi-state tasks and callout boxes
// @author       spingras
// @homepageURL  https://spingras.github.io/hue-md/
// @match        https://github.com/*
// @grant        GM_addStyle
// @run-at       document-end
// ==/UserScript==

// ${notice}
`
await build({
  ...common,
  outfile: path.join(pkgDir, 'userscript', 'hue-md.user.js'),
  banner: { js: header },
  define: { __HUE_CSS__: JSON.stringify(styles) }
})

const kb = (f) => (fs.statSync(path.join(pkgDir, f)).size / 1024).toFixed(1) + ' KB'
console.log(`hue-md github ${version}: extension/content.js ${kb('extension/content.js')}, extension/hue.css ${kb('extension/hue.css')}, userscript/hue-md.user.js ${kb('userscript/hue-md.user.js')}`)
