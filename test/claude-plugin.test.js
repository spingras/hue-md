// Tests for the Claude Code plugin in claude-code-hue/: manifest, bundled CLI,
// the /hue-md:github sync script, and the auto-downgrade hook.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync, existsSync, mkdtempSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { execFileSync, spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { downgrade } from '../md-hue/src/downgrade.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const plugin = join(root, 'claude-code-hue')
const CLI = join(plugin, 'scripts', 'hue-md.cjs')
const SYNC = join(plugin, 'scripts', 'sync.cjs')
const HOOK = join(plugin, 'scripts', 'after-write.cjs')

function tmp () {
  return mkdtempSync(join(tmpdir(), 'hue-plugin-'))
}

function runHook (event, autoDowngrade) {
  const env = { ...process.env }
  delete env.CLAUDE_PLUGIN_OPTION_AUTO_DOWNGRADE
  if (autoDowngrade !== undefined) env.CLAUDE_PLUGIN_OPTION_AUTO_DOWNGRADE = autoDowngrade
  const r = spawnSync(process.execPath, [HOOK], { input: JSON.stringify(event), env, encoding: 'utf8' })
  assert.equal(r.status, 0, r.stderr)
  return r.stdout ? JSON.parse(r.stdout).hookSpecificOutput.additionalContext : ''
}

test('plugin manifest and marketplace entry agree', () => {
  const manifest = JSON.parse(readFileSync(join(plugin, '.claude-plugin', 'plugin.json'), 'utf8'))
  const market = JSON.parse(readFileSync(join(root, '.claude-plugin', 'marketplace.json'), 'utf8'))
  assert.equal(manifest.name, 'hue-md')
  const entry = market.plugins.find((p) => p.name === manifest.name)
  assert.ok(entry, 'marketplace lists the plugin under its manifest name')
  assert.equal(entry.source, './claude-code-hue')
  for (const skill of ['write', 'preview', 'github']) {
    const md = readFileSync(join(plugin, 'skills', skill, 'SKILL.md'), 'utf8')
    assert.match(md, new RegExp(`^---\\nname: ${skill}\\ndescription: .+`), `${skill} has frontmatter`)
  }
})

test('bundled CLI matches the source parser (run npm run build:claude if this fails)', () => {
  const demo = join(root, 'demo', 'demo.hue.md')
  const bundled = execFileSync(process.execPath, [CLI, 'downgrade', demo], { encoding: 'utf8' })
  assert.equal(bundled.trimEnd(), downgrade(readFileSync(demo, 'utf8')).trimEnd())
})

test('sync script writes a marked GitHub copy and refuses a hand-written .md', () => {
  const dir = tmp()
  try {
    const hue = join(dir, 'notes.hue.md')
    const md = join(dir, 'notes.md')
    writeFileSync(hue, '+-- warn Heads up\n| Check {warn: this}.\n+--\n')

    execFileSync(process.execPath, [SYNC, hue])
    const out = readFileSync(md, 'utf8')
    assert.match(out, /^<!-- Generated by hue-md from notes\.hue\.md\./)
    assert.match(out, /> \[!WARNING\]/)

    // A generated file may be refreshed without --force.
    execFileSync(process.execPath, [SYNC, hue])

    writeFileSync(md, '# My own notes\n')
    const refused = spawnSync(process.execPath, [SYNC, hue], { encoding: 'utf8' })
    assert.equal(refused.status, 1)
    assert.match(refused.stderr, /not generated by hue-md/)
    assert.equal(readFileSync(md, 'utf8'), '# My own notes\n')

    execFileSync(process.execPath, [SYNC, hue, '--force'])
    assert.match(readFileSync(md, 'utf8'), /\[!WARNING\]/)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})

test('hook does nothing unless auto_downgrade is on', () => {
  const dir = tmp()
  try {
    const hue = join(dir, 'a.hue.md')
    writeFileSync(hue, '{ok: done}\n')
    const event = { cwd: dir, tool_name: 'Write', tool_input: { file_path: hue } }
    assert.equal(runHook(event, undefined), '')
    assert.equal(runHook(event, 'false'), '')
    assert.equal(existsSync(join(dir, 'a.md')), false)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})

test('hook writes the GitHub copy for .hue.md, ignores other files, never overwrites hand-written .md', () => {
  const dir = tmp()
  try {
    writeFileSync(join(dir, 'a.hue.md'), '{warn: careful}\n')
    const ctx = runHook({ cwd: dir, tool_name: 'Edit', tool_input: { file_path: 'a.hue.md' } }, 'true')
    assert.match(ctx, /updated the GitHub copy/)
    assert.match(readFileSync(join(dir, 'a.md'), 'utf8'), /\*\*careful\*\*/)

    writeFileSync(join(dir, 'plain.md'), 'x\n')
    assert.equal(runHook({ cwd: dir, tool_name: 'Write', tool_input: { file_path: join(dir, 'plain.md') } }, 'true'), '')

    writeFileSync(join(dir, 'b.hue.md'), '{ok: done}\n')
    writeFileSync(join(dir, 'b.md'), 'mine\n')
    const refused = runHook({ cwd: dir, tool_name: 'Write', tool_input: { file_path: join(dir, 'b.hue.md') } }, 'true')
    assert.match(refused, /did not update/)
    assert.equal(readFileSync(join(dir, 'b.md'), 'utf8'), 'mine\n')

    assert.equal(runHook({ garbage: true }, 'true'), '')
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})
