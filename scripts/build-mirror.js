// Builds the standalone repository for a plugin that has to live in a repo of
// its own (Obsidian reads manifest.json from the root of the plugin's repo).
// The monorepo stays the only source: the mirror is generated from it on every
// release by .github/workflows/mirrors.yml and is never edited by hand.
//
//   node scripts/build-mirror.js obsidian --out dist/mirror/hue-md-obsidian [--check]
//
// --check also runs the mirror's own build inside the output folder and fails
// unless it produces the same main.js, manifest.json and styles.css as
// packages/obsidian-hue. The test in packages/obsidian-hue/test/mirror.test.js
// runs this on every `npm test`, so a mirror that would drift fails CI.
//
// Only Obsidian for now; hue-md.nvim gets its own entry in TARGETS when its
// repository exists.

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rootPkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const installed = (name) => JSON.parse(fs.readFileSync(path.join(root, 'node_modules', name, 'package.json'), 'utf8')).version
const MARKER = '.hue-mirror'

// Replaces `from` with `to` exactly once, so a moved import fails loudly.
function rewrite (text, from, to, file) {
  const parts = text.split(from)
  if (parts.length !== 2) throw new Error(`${file}: expected "${from}" exactly once, found ${parts.length - 1}`)
  return parts.join(to)
}

// Every file in src/ that the given src/ files import, followed recursively.
function hueSources (entries) {
  const seen = new Set()
  const visit = (rel) => {
    if (seen.has(rel)) return
    seen.add(rel)
    const text = fs.readFileSync(path.join(root, 'src', rel), 'utf8')
    for (const m of text.matchAll(/(?:from|import)\s+'(\.{1,2}\/[^']+)'/g)) {
      const next = path.posix.normalize(path.posix.join(path.posix.dirname(rel), m[1]))
      if (next.startsWith('..')) throw new Error(`src/${rel} imports ${m[1]}, outside src/: the mirror cannot follow it`)
      visit(next)
    }
  }
  entries.forEach(visit)
  return [...seen].sort()
}

// A package-lock.json for the mirror with the exact versions the monorepo's
// lock has, so `npm ci` there installs the same markdown-it and esbuild the
// monorepo built and tested with.
function mirrorLock (name, version, deps, devDeps) {
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'))
  const entry = (n) => {
    const e = lock.packages['node_modules/' + n]
    if (!e) throw new Error(`package-lock.json has no top-level node_modules/${n}: the mirror lock cannot be made`)
    return e
  }
  const closure = (names) => {
    const seen = new Set()
    const walk = (n) => {
      if (seen.has(n)) return
      seen.add(n)
      const e = entry(n)
      for (const d of Object.keys({ ...e.dependencies, ...e.optionalDependencies })) walk(d)
    }
    names.forEach(walk)
    return seen
  }
  const prod = closure(deps)
  const dev = closure(devDeps)
  const packages = {
    '': {
      name,
      version,
      license: rootPkg.license,
      dependencies: Object.fromEntries(deps.map((d) => [d, entry(d).version])),
      devDependencies: Object.fromEntries(devDeps.map((d) => [d, entry(d).version]))
    }
  }
  for (const n of [...new Set([...prod, ...dev])].sort()) {
    const { dev: _d, devOptional: _o, peer: _p, ...e } = entry(n)
    if (!prod.has(n)) e.dev = true
    packages['node_modules/' + n] = e
  }
  return { name, version, lockfileVersion: 3, requires: true, packages }
}

// The mirror's own release workflow: a pushed tag builds the plugin from the
// repository's source and attaches the three files Obsidian downloads.
const OBSIDIAN_RELEASE_WORKFLOW = `# Generated by scripts/build-mirror.js in spingras/hue-md; do not edit here.
name: Release

on:
  push:
    tags:
      - "*"

permissions:
  contents: write

jobs:
  release:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: "22"
      - run: npm ci
      - run: npm run build
      - name: The tag is the manifest version
        run: test "$(node -p "require('./manifest.json').version")" = "\${GITHUB_REF_NAME}"
      - name: Create the release with main.js, manifest.json and styles.css
        env:
          GH_TOKEN: \${{ github.token }}
        run: |
          if gh release view "\${GITHUB_REF_NAME}" >/dev/null 2>&1; then
            gh release upload "\${GITHUB_REF_NAME}" main.js manifest.json styles.css --clobber
          else
            gh release create "\${GITHUB_REF_NAME}" main.js manifest.json styles.css --title "\${GITHUB_REF_NAME}" \\
              --notes "Hue MD for Obsidian \${GITHUB_REF_NAME}. Changes: https://github.com/spingras/hue-md/releases/tag/v\${GITHUB_REF_NAME}"
          fi
`

function obsidianReadme (version) {
  const src = fs.readFileSync(path.join(root, 'packages/obsidian-hue/README.md'), 'utf8')
  const cut = src.indexOf('\n## Install')
  if (cut === -1) throw new Error('packages/obsidian-hue/README.md: no "## Install" heading to cut at')
  const features = rewrite(src.slice(0, cut).trimEnd(),
    '(`src/index.js` and `src/core.js` at the repo root)', '(in `hue/`, copied from the Hue MD repository)', 'packages/obsidian-hue/README.md')
  return `${features}

## Install

In Obsidian: **Settings → Community plugins → Browse**, search for **Hue MD** and select **Install**, then **Enable**.

By hand: download \`main.js\`, \`manifest.json\` and \`styles.css\` from the [latest release](https://github.com/spingras/hue-md-obsidian/releases/latest) into your vault's \`.obsidian/plugins/hue-md/\` folder, then enable **Hue MD** under **Settings → Community plugins**.

## Source, issues and changes

This repository is generated from [spingras/hue-md](https://github.com/spingras/hue-md) (\`packages/obsidian-hue\`) on every Hue MD release; this is version ${version}. Please open issues and pull requests there: changes made here are overwritten by the next release.

\`npm install\` and \`npm run build\` rebuild \`main.js\`, \`manifest.json\` and \`styles.css\` from \`src/\` and \`hue/\`.

## License

MIT, see [LICENSE](LICENSE).
`
}

function buildObsidian (out) {
  const version = rootPkg.version
  const pkgDir = path.join(root, 'packages/obsidian-hue')
  const write = (rel, text) => {
    fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true })
    fs.writeFileSync(path.join(out, rel), text)
  }

  // The plugin source, with imports pointing at hue/ instead of the monorepo's src/.
  write('src/main.js', rewrite(fs.readFileSync(path.join(pkgDir, 'src/main.js'), 'utf8'), "'../../../src/dom.js'", "'../hue/dom.js'", 'src/main.js'))
  write('src/obsidian.css', fs.readFileSync(path.join(pkgDir, 'src/obsidian.css'), 'utf8'))
  write('src/manifest.json', fs.readFileSync(path.join(pkgDir, 'src/manifest.json'), 'utf8'))

  let build = fs.readFileSync(path.join(pkgDir, 'scripts/build.mjs'), 'utf8')
  build = rewrite(build, "'../../../src/index.js'", "'../hue/index.js'", 'scripts/build.mjs')
  build = rewrite(build, "'../../../src/palette.js'", "'../hue/palette.js'", 'scripts/build.mjs')
  build = rewrite(build, "const root = path.resolve(pkgDir, '..', '..')", 'const root = pkgDir', 'scripts/build.mjs')
  build = rewrite(build, '// Needs the root dev dependencies (esbuild): run `npm install` at the repo root once.', '// Needs the dev dependencies (esbuild): run `npm install` once.', 'scripts/build.mjs')
  write('scripts/build.mjs', build)

  // The Hue parser files the plugin and its build use, unchanged.
  for (const rel of hueSources(['dom.js', 'index.js', 'palette.js'])) {
    write(path.posix.join('hue', rel), fs.readFileSync(path.join(root, 'src', rel), 'utf8'))
  }

  // Obsidian reads manifest.json from the repository root, so it is committed built.
  const manifest = JSON.parse(fs.readFileSync(path.join(pkgDir, 'src/manifest.json'), 'utf8'))
  manifest.version = version
  write('manifest.json', JSON.stringify(manifest, null, 2) + '\n')
  write('versions.json', JSON.stringify({ [version]: manifest.minAppVersion }, null, 2) + '\n')

  write('package.json', JSON.stringify({
    name: 'hue-md-obsidian',
    version,
    private: true,
    description: manifest.description,
    author: rootPkg.author,
    license: rootPkg.license,
    type: 'module',
    scripts: { build: 'node scripts/build.mjs' },
    dependencies: { 'markdown-it': installed('markdown-it') },
    devDependencies: { esbuild: installed('esbuild') }
  }, null, 2) + '\n')
  write('package-lock.json', JSON.stringify(mirrorLock('hue-md-obsidian', version, ['markdown-it'], ['esbuild']), null, 2) + '\n')
  // Built files at the root only: src/main.js is the source and must be committed.
  write('.gitignore', 'node_modules/\n/main.js\n/styles.css\n')
  // LF everywhere, as in the monorepo: a Windows checkout must build the same styles.css.
  write('.gitattributes', '* text=auto eol=lf\n')
  write('.github/workflows/release.yml', OBSIDIAN_RELEASE_WORKFLOW)
  write('LICENSE', fs.readFileSync(path.join(root, 'LICENSE'), 'utf8'))
  write('README.md', obsidianReadme(version))
  return { version, assets: ['main.js', 'manifest.json', 'styles.css'], compareWith: pkgDir }
}

const TARGETS = { obsidian: buildObsidian }

// esbuild writes `// path/to/file.js` above each module; the paths differ
// between the two layouts, the code must not.
const normalize = (text) => text.replace(/^\s*\/\/ \S+\.(?:m?js|json)\r?\n/gm, '')

export function buildMirror (target, out, { check = false } = {}) {
  const fn = TARGETS[target]
  if (!fn) throw new Error(`unknown target "${target}"; known: ${Object.keys(TARGETS).join(', ')}`)
  out = path.resolve(out)
  // Only ever clear a folder this script made.
  if (fs.existsSync(out)) {
    if (!fs.existsSync(path.join(out, MARKER))) throw new Error(`${out} exists and was not made by build-mirror.js; refusing to clear it`)
    fs.rmSync(out, { recursive: true, force: true })
  }
  fs.mkdirSync(out, { recursive: true })
  const result = fn(out)
  // Not part of the published tree (publish-mirror.sh skips it).
  fs.writeFileSync(path.join(out, MARKER), `${target} ${result.version}\n`)
  if (check) checkMirror(out, result)
  return result
}

// Runs the mirror's own build in `out` and compares its files with the package's.
export function checkMirror (out, result) {
  execFileSync(process.execPath, ['scripts/build.mjs'], { cwd: out, stdio: 'pipe' })
  for (const f of result.assets) {
    const a = normalize(fs.readFileSync(path.join(out, f), 'utf8'))
    const b = normalize(fs.readFileSync(path.join(result.compareWith, f), 'utf8'))
    if (a !== b) throw new Error(`mirror build of ${f} differs from ${path.relative(root, result.compareWith)}/${f}`)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  const target = args[0]
  const outAt = args.indexOf('--out')
  if (!target || outAt === -1 || !args[outAt + 1]) {
    console.error('usage: node scripts/build-mirror.js <obsidian> --out <dir> [--check]')
    process.exit(2)
  }
  try {
    const r = buildMirror(target, args[outAt + 1], { check: args.includes('--check') })
    console.log(`mirror ${target} ${r.version} written to ${args[outAt + 1]}${args.includes('--check') ? ', its own build matches' : ''}`)
  } catch (e) {
    console.error(e.message)
    process.exit(1)
  }
}
