// Generates the editor snippets in snippets/ from the VS Code snippets
// (packages/vscode-hue/snippets/hue.json), so every editor gets the same set:
//   snippets/sublime/*.sublime-snippet   Sublime Text
//   snippets/ultisnips/hue.snippets      UltiSnips (Vim / Neovim)
//   snippets/luasnip/hue.lua             LuaSnip (Neovim)
//   snippets/obsidian/*.md               Obsidian templates (block snippets)
//
// Run: node scripts/build-snippets.js
// test/snippets.test.js checks the files are up to date and that each
// snippet's default text renders as the Hue it promises.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = 'packages/vscode-hue/snippets/hue.json'
const NOTICE = `Generated by scripts/build-snippets.js from ${SOURCE}; do not edit.`

export function loadSnippets () {
  const json = JSON.parse(fs.readFileSync(path.join(root, SOURCE), 'utf8'))
  return Object.entries(json).map(([name, s]) => ({
    name,
    prefixes: Array.isArray(s.prefix) ? s.prefix : [s.prefix],
    body: Array.isArray(s.body) ? s.body.join('\n') : s.body,
    description: s.description || name
  }))
}

// ${1|a,b|} choices -> ${1:a}, for editors without choice placeholders.
const noChoices = (body) => body.replace(/\$\{(\d+)\|([^|}]*?)(?:,[^|}]*)*\|\}/g, (_, n, first) => `\${${n}:${first}}`)

// The text a snippet inserts when every placeholder keeps its default.
export function defaultText (body) {
  let out = noChoices(body)
  let prev
  do {
    prev = out
    out = out.replace(/\$\{\d+:([^${}]*)\}/g, '$1')
  } while (out !== prev)
  return out.replace(/\$\{?\d+\}?/g, '')
}

// A snippet that starts a block (box, task) rather than text inside a line.
const isBlock = (s) => /^(\+--|╭──|- \[)/.test(s.body)

function slug (s) {
  return s.prefixes[0].replace(/[^a-z0-9-]/gi, '')
}

function sublime (s) {
  return `<snippet>
	<!-- ${NOTICE} -->
	<content><![CDATA[
${noChoices(s.body)}
]]></content>
	<tabTrigger>${s.prefixes[0]}</tabTrigger>
	<scope>text.html.markdown</scope>
	<description>Hue: ${s.description.replace(/^Insert (a |an )?/, '')}</description>
</snippet>
`
}

function ultisnips (all) {
  const out = [`# Hue MD snippets for UltiSnips. ${NOTICE}`, '']
  for (const s of all) {
    for (const p of s.prefixes) {
      // Blocks only at the start of a line (b); inline ones after a space or at
      // the start (UltiSnips' default; its `w` option breaks hyphenated triggers like hue-span).
      const desc = `"${s.description.replace(/"/g, "'")}"`
      out.push(`snippet ${p} ${desc}${isBlock(s) ? ' b' : ''}`, noChoices(s.body), 'endsnippet', '')
    }
  }
  return out.join('\n')
}

const luaString = (str) => {
  let eq = ''
  while (str.includes(']' + eq + ']')) eq += '='
  return `[${eq}[${str}]${eq}]`
}

function luasnip (all) {
  const out = [
    `-- Hue MD snippets for LuaSnip. ${NOTICE}`,
    '-- Bodies use VS Code snippet syntax, which LuaSnip parses itself (choices included).',
    '-- Load with: require("luasnip").add_snippets("markdown", require("hue"))',
    'local ls = require("luasnip")',
    'local parse = ls.parser.parse_snippet',
    '',
    'return {'
  ]
  for (const s of all) {
    for (const p of s.prefixes) {
      out.push(`  parse({ trig = ${JSON.stringify(p)}, dscr = ${JSON.stringify(s.description)} }, ${luaString(s.body)}),`)
    }
  }
  out.push('}', '')
  return out.join('\n')
}

const OBSIDIAN_NAMES = {
  'Hue Info Box': 'Hue - Info Box',
  'Hue Warning Box': 'Hue - Warn Box',
  'Hue OK / Success Box': 'Hue - OK Box',
  'Hue Note Box': 'Hue - Note Box',
  'Hue Danger Box': 'Hue - Danger Box',
  'Hue Split Boxes (Side-by-Side)': 'Hue - Side-by-Side Boxes',
  'Hue Rounded Box': 'Hue - Rounded Box',
  'Hue Multi-State Task': 'Hue - Task'
}

// { 'snippets/…': content }
export function snippetFiles () {
  const all = loadSnippets()
  const files = {}
  for (const s of all) files[`snippets/sublime/${slug(s)}.sublime-snippet`] = sublime(s)
  files['snippets/ultisnips/hue.snippets'] = ultisnips(all)
  files['snippets/luasnip/hue.lua'] = luasnip(all)
  for (const s of all) {
    const name = OBSIDIAN_NAMES[s.name]
    if (name) files[`snippets/obsidian/${name}.md`] = defaultText(s.body) + '\n'
  }
  return files
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const dir of ['snippets/sublime', 'snippets/obsidian']) {
    for (const f of fs.readdirSync(path.join(root, dir))) fs.rmSync(path.join(root, dir, f))
  }
  const files = snippetFiles()
  for (const [file, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
    fs.writeFileSync(path.join(root, file), content)
  }
  console.log(`wrote ${Object.keys(files).length} snippet files from ${SOURCE}`)
}
